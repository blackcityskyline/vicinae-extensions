import { Action, ActionPanel, Icon, Keyboard, List } from "@vicinae/api";
import { useCallback, useEffect, useState } from "react";

import { alive, pendingDeadline } from "~/utils/process.ts";
import {
	chooseSource,
	finishExpired,
	customChannel,
	durations,
	readPrefs,
	resetSession,
	skip,
	toggle,
} from "~/api/session.ts";
import { readState } from "~/api/store.ts";
import { SOURCES, sourceName, type Source } from "~/utils/music.ts";
import { clockText, emptyState, expired, leftMs, musicWanted, phaseLabel, type State } from "~/utils/state.ts";

const KIND: Record<Source["kind"], string> = {
	youtube: "YouTube live · mpv + yt-dlp",
	ambient: "Offline loop",
	generated: "Generated by mpv",
};

function timerIcon(state: State) {
	if (state.phase === "break") return Icon.Moon;
	if (!state.running && state.phase !== "idle") return Icon.Pause;
	return Icon.Clock;
}

export default function Command() {
	const [state, setState] = useState<State | null>(null);
	const refresh = useCallback(async () => {
		setState(await readState());
	}, []);

	useEffect(() => {
		let live = true;
		const tick = async () => {
			const next = await readState();
			if (!live) return;
			// The detached deadline shell may be dead without having launched
			// the advance command; that is the only case the view takes over.
			if (expired(next, Date.now()) && !pendingDeadline(next.timerPid)) {
				await finishExpired();
				if (live) setState(await readState());
				return;
			}
			setState(next);
		};
		void tick();
		const interval = setInterval(() => void tick(), 1000);
		return () => {
			live = false;
			clearInterval(interval);
		};
	}, []);

	const prefs = readPrefs();
	const d = durations(prefs);
	const current = state ?? emptyState();
	const left = leftMs(current, Date.now(), d.focusMs);
	const playing = alive(current.musicPid);
	const wanted = musicWanted(current, d.keepMusicOnBreak);
	const musicState = current.source === "" ? "No music" : playing ? sourceName(current.source) : wanted ? "Music stopped" : "Paused";
	const custom = customChannel(prefs);
	const sources: Source[] = custom
		? [...SOURCES, { name: "Custom channel", url: custom, kind: "youtube" }]
		: SOURCES;

	const actions = (
		<>
			<Action
				title={current.running ? "Pause" : current.phase === "idle" ? "Start Focus" : "Resume"}
				icon={current.running ? Icon.Pause : Icon.Play}
				onAction={async () => setState(await toggle())}
			/>
			<Action title="Skip Phase" icon={Icon.Forward} onAction={async () => setState(await skip())} />
			<Action
				title="Reset"
				icon={Icon.ArrowCounterClockwise}
				shortcut={Keyboard.Shortcut.Common.RemoveAll}
				onAction={async () => setState(await resetSession())}
			/>
			<Action
				title="Refresh"
				icon={Icon.ArrowClockwise}
				shortcut={Keyboard.Shortcut.Common.Refresh}
				onAction={refresh}
			/>
		</>
	);

	return (
		<List isShowingDetail={false} isLoading={state === null} searchBarPlaceholder="Search music…">
			<List.Section title="Timer">
				<List.Item
					id="timer"
					title={clockText(left)}
					subtitle={`${phaseLabel(current)} · ${current.sessionsDone} session${current.sessionsDone === 1 ? "" : "s"} done`}
					icon={timerIcon(current)}
					keywords={["pomodoro", "timer", "focus", "break"]}
					accessories={[{ text: musicState }]}
					actions={<ActionPanel>{actions}</ActionPanel>}
				/>
			</List.Section>
			<List.Section title="Music">
				{sources.map((source) => {
					const active = current.source === source.url;
					return (
						<List.Item
							key={source.url}
							id={`source-${source.url}`}
							title={source.name}
							subtitle={KIND[source.kind]}
							icon={active ? Icon.Speaker : Icon.Music}
							keywords={[source.kind, "music", "sound"]}
							accessories={active ? [{ text: playing ? "Playing" : "Selected" }] : undefined}
							actions={
								<ActionPanel>
									<Action
										title={active ? "Stop Music" : "Use This Music"}
										icon={active ? Icon.Stop : Icon.Play}
										onAction={async () => {
											await chooseSource(active ? "" : source.url);
											setState(await readState());
										}}
									/>
									{actions}
								</ActionPanel>
							}
						/>
					);
				})}
				<List.Item
					id="source-none"
					title="No Music"
					subtitle="Silence"
					icon={Icon.SpeakerOff}
					keywords={["silence", "off"]}
					accessories={current.source === "" ? [{ text: "Selected" }] : undefined}
					actions={
						<ActionPanel>
							<Action
								title="Stop Music"
								icon={Icon.Stop}
								onAction={async () => {
									await chooseSource("");
									setState(await readState());
								}}
							/>
							{actions}
						</ActionPanel>
					}
				/>
			</List.Section>
		</List>
	);
}
