const lines: string[] = [];
lines.push("#!/bin/bash");
lines.push("");
lines.push('backend=""');
lines.push("args=()");
lines.push("while (($#)); do");
lines.push('  case "$1" in');
lines.push("    --backend)");
lines.push('      backend=${2:?--backend needs a value}');
lines.push("      shift 2");
lines.push("      ;;");
lines.push("    *)");
lines.push('      args+=("$1")');
lines.push("      shift");
lines.push("      ;;");
lines.push("  esac");
lines.push("done");
lines.push('set -- "${args[@]}"');
lines.push("");
lines.push('url=${1:?usage: webapp-launch [--backend <bin>] <url> [browser flags...]}');
lines.push("shift");
lines.push("");
lines.push('if [[ -z $backend || $backend == "auto" ]]; then');
lines.push('  backend=""');
lines.push("fi");
lines.push("");
lines.push('exec_bin=""');
lines.push("");
lines.push("localBin() {");
lines.push('  [[ -x "$HOME/.local/bin/$1" ]] && { printf \'%s\\n\' "$HOME/.local/bin/$1"; return 0; }');
lines.push("  return 1");
lines.push("}");
lines.push("tryBin() {");
lines.push('  command -v "$1" 2>/dev/null || localBin "$1"');
lines.push("}");
lines.push("");
lines.push('if [[ -n $backend ]]; then');
lines.push('  case "$backend" in');
lines.push("    helium)");
lines.push('      exec_bin=$(tryBin "helium-browser") || exec_bin=$(tryBin "helium")');
lines.push("      ;;");
lines.push("    chromium)");
lines.push('      exec_bin=$(tryBin "chromium") || exec_bin=$(tryBin "chromium-browser")');
lines.push("      ;;");
lines.push("    thorium)");
lines.push('      exec_bin=$(tryBin "thorium") || exec_bin=$(tryBin "thorium-browser")');
lines.push("      ;;");
lines.push("    brave)");
lines.push('      exec_bin=$(tryBin "brave-browser") || exec_bin=$(tryBin "brave")');
lines.push("      ;;");
lines.push("    chrome)");
lines.push('      exec_bin=$(tryBin "google-chrome") || exec_bin=$(tryBin "google-chrome-stable") || exec_bin=$(tryBin "chrome")');
lines.push("      ;;");
lines.push("    *)");
lines.push('      exec_bin=$(tryBin "$backend")');
lines.push('      if [[ -z $exec_bin ]]; then exec_bin=$(tryBin "${backend%-browser}"); fi');
lines.push('      if [[ -z $exec_bin ]]; then exec_bin=$(tryBin "${backend}-browser"); fi');
lines.push("      ;;");
lines.push("  esac");
lines.push("fi");
lines.push("");
lines.push('if [[ -z $exec_bin ]]; then');
lines.push('  browser=$(xdg-settings get default-web-browser 2>/dev/null)');
lines.push("");
lines.push("  case $browser in");
lines.push("  chromium*|chrome*|google-chrome*|brave*|microsoft-edge*|opera*|vivaldi*|helium*|thorium*)");
lines.push("    exec_bin=$(sed -n 's/^Exec=\\([^ ]*\\).*/\\1/p' \"$HOME/.local/share/applications/$browser\" \"/usr/share/applications/$browser\" 2>/dev/null | head -1)");
lines.push("    exec_bin=${exec_bin//\"/}");
lines.push("    ;;");
lines.push("  userapp-*)");
lines.push('    case ${browser,,} in');
lines.push("    *chromium*|*chrome*|*brave*|*edge*|*opera*|*vivaldi*|*helium*|*thorium*)");
lines.push("      exec_bin=$(sed -n 's/^Exec=\\([^ ]*\\).*/\\1/p' \"$HOME/.local/share/applications/$browser\" \"/usr/share/applications/$browser\" 2>/dev/null | head -1)");
lines.push("      exec_bin=${exec_bin//\"/}");
lines.push("      ;;");
lines.push("    esac");
lines.push("    ;;");
lines.push("  esac");
lines.push("");
lines.push('  if [[ -z $exec_bin ]]; then');
lines.push("    for candidate in helium-browser helium chromium thorium thorium-browser brave-browser brave google-chrome-stable google-chrome chrome vivaldi microsoft-edge-stable microsoft-edge opera; do");
lines.push('      if tryBin "$candidate" >/dev/null; then');
lines.push('        exec_bin=$candidate');
lines.push("        break");
lines.push("      fi");
lines.push("    done");
lines.push("  fi");
lines.push("fi");
lines.push("");
lines.push('if [[ -z $exec_bin ]]; then');
lines.push('  command -v notify-send >/dev/null && notify-send "Web app" "No supported browser found (Chromium-family only: helium, chromium, thorium, brave, chrome)"');
lines.push("  exit 1");
lines.push("fi");
lines.push("");
lines.push('exec setsid "$exec_bin" --app="$url" "$@"');
lines.push("");

export const LAUNCHER_SCRIPT = lines.join("\n");
