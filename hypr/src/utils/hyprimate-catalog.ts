/**
 * hyprimate's configuration surface: the plugin's 257 registered settings plus
 * the 52 shared `window.options.<style>.<leaf>` keys the plugin derives from
 * them, taken from its own `config/settings.json`. Keys are colon paths under
 * `plugin:hyprimate:`; `path` is the dotted form used in Lua and in
 * `hyprctl getoption`. Regenerate when the plugin's schema changes.
 */

export type HyprimateScope =
	| "global"
	| "shared"
	| "open"
	| "close"
	| "movement"
	| "workspace";

export type HyprimateType = "float" | "int" | "string" | "boolean" | "color" | "set";

export interface HyprimateOption {
	/** Colon path below `plugin:hyprimate:`. */
	key: string;
	/** Dotted path, as used in Lua config and `hyprctl getoption`. */
	path: string;
	type: HyprimateType;
	/** Which table the option lives in: shared style values, one animation, or a global switch. */
	scope: HyprimateScope;
	/** Style or workspace style the option belongs to; absent for global settings. */
	style?: string;
	default: string | number | boolean;
	min?: number;
	max?: number;
	choices?: string[];
	label: string;
	description: string;
}

