export type PresetKind = "animation" | "border" | "shader";
export type PresetOrigin = "shipped" | "personal";

export interface Preset {
	slug: string;
	name: string;
	tag: string;
	description: string;
	source: string;
	origin: PresetOrigin;
}

export interface AnimState {
	enabled: boolean;
	last: string | null;
	border: string | null;
	shader: string | null;
}

export interface PresetMeta {
	name?: string;
	tag?: string;
	description?: string;
}

// Synthetic first entry in each list. It removes the layer instead of applying
// a file, so "off" means your own Hyprland config: an identity shader would
// still cost a render pass, and a "border off" file would not restore a
// borderless config the user already has.
export const OFF_SLUG = "__off";

const OFF: Record<PresetKind, Pick<Preset, "name" | "description">> = {
	animation: { name: "No animations", description: "Turn animations off and drop the animation layer." },
	border: { name: "No borders", description: "Drop the border layer; your own Hyprland border settings apply." },
	shader: { name: "No shaders", description: "Drop the screen shader; your own Hyprland config applies." },
};

export function offPreset(kind: PresetKind): Preset {
	return {
		slug: OFF_SLUG,
		name: OFF[kind].name,
		tag: "Off",
		description: OFF[kind].description,
		source: "",
		origin: "shipped",
	};
}

// Lua and GLSL comments both carry the directives: a shader is a .frag the
// compositor reads, so its metadata has to live in a comment. Shipped shaders
// use the original `//@Title: ...` spelling, so accept both.
const META = /^(?:--|\/\/)\s*@(name|title|tag|description|desc)\s*:?\s*(.+?)\s*$/i;

export function parseMeta(source: string): PresetMeta {
	const meta: PresetMeta = {};
	for (const line of source.split("\n")) {
		const match = META.exec(line.trim());
		const key = match?.[1]?.toLowerCase();
		const value = match?.[2];
		if (!key || !value) continue;
		if (key === "name" || key === "title") meta.name = value;
		else if (key === "tag") meta.tag = value;
		else meta.description = value;
	}
	return meta;
}

export function titleFromSlug(slug: string): string {
	return slug
		.split(/[-_]/)
		.filter(Boolean)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join(" ");
}

const DEFAULT_TAG: Record<PresetKind, string> = {
	animation: "Preset",
	border: "Border",
	shader: "Shader",
};

export function toPreset(slug: string, source: string, origin: PresetOrigin, kind: PresetKind): Preset {
	const meta = parseMeta(source);
	return {
		slug,
		name: meta.name ?? titleFromSlug(slug),
		tag: meta.tag ?? (origin === "personal" ? "Personal" : DEFAULT_TAG[kind]),
		description: meta.description ?? "",
		source,
		origin,
	};
}

// A personal file with the same slug replaces the shipped preset: copying a
// preset into the user's directory is how you fork it. It stays under Your
// Presets, so the file that is actually applied is always visible.
export function mergePresets(shipped: Preset[], personal: Preset[]): Preset[] {
	const taken = new Set(personal.map((preset) => preset.slug));
	return [...shipped.filter((preset) => !taken.has(preset.slug)), ...personal];
}

export interface Composition {
	enabled: boolean;
	animation?: Pick<Preset, "slug" | "source"> | null;
	border?: Pick<Preset, "slug" | "source"> | null;
	// Pixels, from the Border Size preference. Emitted after the preset so the
	// hardcoded size in the shipped files does not win.
	borderSize?: number;
	shader?: { slug: string; path: string } | null;
}

// The base layer must come first: the preset is what overrides it. Writing the
// pair in the other order would let the base re-enable a leaf the preset turned
// off, which is exactly the bug this extension exists to fix.
export function composeActive(base: string, parts: Composition): string {
	const lines = ["-- Generated by the Hypr extension. Do not edit.", ""];

	if (parts.enabled) lines.push(base.trim());
	else lines.push("hl.config({ animations = { enabled = false } })");

	if (parts.enabled && parts.animation) {
		lines.push("", `-- animation: ${parts.animation.slug}`, parts.animation.source.trim());
	}
	if (parts.border) {
		lines.push("", `-- border: ${parts.border.slug}`, parts.border.source.trim());
		if (parts.borderSize !== undefined) {
			lines.push(`hl.config({ general = { border_size = ${parts.borderSize} } })`);
		}
	}
	if (parts.shader) {
		lines.push(
			"",
			`-- shader: ${parts.shader.slug}`,
			`hl.config({ decoration = { screen_shader = ${JSON.stringify(parts.shader.path)} } })`,
		);
	}
	lines.push("");
	return lines.join("\n");
}

export function parseState(text: string): AnimState {
	let enabled = false;
	let last: string | null = null;
	let border: string | null = null;
	let shader: string | null = null;
	for (const line of text.split("\n")) {
		const match = /^\s*(enabled|last|border|shader)\s*=\s*(.*?)\s*$/.exec(line);
		const key = match?.[1];
		const value = match?.[2];
		if (!key) continue;
		if (key === "enabled") enabled = value === "true";
		else if (key === "last") last = value || null;
		else if (key === "border") border = value || null;
		else shader = value || null;
	}
	return { enabled, last, border, shader };
}

export function formatState(state: AnimState): string {
	return [
		`enabled=${state.enabled}`,
		`last=${state.last ?? ""}`,
		`border=${state.border ?? ""}`,
		`shader=${state.shader ?? ""}`,
		"",
	].join("\n");
}
